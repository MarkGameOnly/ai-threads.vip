const KEYS = Object.keys(DEFAULTS);

export async function getSettings() {
  const stored = await chrome.storage.local.get(KEYS);
  const s = { ...DEFAULTS, ...stored };
  s.sel = { ...DEFAULTS.sel, ...(stored.sel || {}) };
  s.hunter = { ...DEFAULTS.hunter, ...(stored.hunter || {}) };
  s.dm = { ...DEFAULTS.dm, ...(stored.dm || {}) };
  s.safe = { ...DEFAULTS.safe, ...(stored.safe || {}) };
  s.source = { ...DEFAULTS.source, ...(stored.source || {}) };
  s.source.queries = Array.isArray(s.source.queries) ? s.source.queries : [];
  s.schedule = { ...DEFAULTS.schedule, ...(stored.schedule || {}) };
  return s;
}
export async function setSettings(patch) {
  await chrome.storage.local.set(patch);
  return getSettings();
}

// счётчики дня
// Локальная дата, а не UTC: при часовом поясе UTC+5 дневной лимит
// обнулялся в 05:00 по местному времени.
function today() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}
export async function getCounters() {
  const { _counters } = await chrome.storage.local.get("_counters");
  if (_counters?.date === today()) return _counters;
  const fresh = { date: today(), comments: 0, posts: 0 };
  await chrome.storage.local.set({ _counters: fresh });
  return fresh;
}
export async function bumpCounter(field, by = 1) {
  const c = await getCounters();
  c[field] = (c[field] || 0) + by;
  await chrome.storage.local.set({ _counters: c });
  return c;
}

// ── Состояние движка ──────────────────────────────────────
// Хранится в storage, а не в памяти вкладки: авто-режим переходит между
// лентой и страницами поиска, при навигации content-script перезапускается
// и должен подхватить работу с того же места.
const ENGINE_DEFAULT = {
  running: false,
  mode: "auto",       // auto | manual
  src: "feed",        // feed | search
  qi: 0,              // индекс текущего поискового запроса
  queries: [],
  rotatedAt: 0,
  retry: "",          // код поста, на который заходим второй попыткой
  stats: { seen: 0, generated: 0, sent: 0, skipped: 0 },
  startedAt: 0,
};

export async function getEngine() {
  const { _engine } = await chrome.storage.local.get("_engine");
  return { ...ENGINE_DEFAULT, ...(_engine || {}) };
}
export async function setEngine(patch) {
  const e = { ...(await getEngine()), ...patch };
  await chrome.storage.local.set({ _engine: e });
  return e;
}
export async function bumpStat(field, by = 1) {
  const e = await getEngine();
  e.stats = { ...e.stats, [field]: (e.stats?.[field] || 0) + by };
  await chrome.storage.local.set({ _engine: e });
  return e;
}
export async function resetEngine() {
  await chrome.storage.local.set({ _engine: { ...ENGINE_DEFAULT } });
}

// ── Очередь подтверждения (ручной режим) ──────────────────
export async function pendingList() {
  const { pending } = await chrome.storage.local.get("pending");
  return pending || [];
}
export async function pendingAdd(item) {
  const list = await pendingList();
  if (list.some((x) => x.code === item.code)) return list;
  list.unshift({ ...item, at: Date.now() });
  const cut = list.slice(0, 60);
  await chrome.storage.local.set({ pending: cut });
  return cut;
}
export async function pendingRemove(code) {
  const list = (await pendingList()).filter((x) => x.code !== code);
  await chrome.storage.local.set({ pending: list });
  return list;
}
