/** Развернуть пресет ниши в готовый патч настроек. */
export function nichePatch(key, current = {}) {
  const n = NICHE_PRESETS[key];
  if (!n) return {};
  return {
    activeNiche: key,
    niche: n.niche,
    commentPrompt: n.comment,
    postPrompt: n.post,
    dm: { ...(current.dm || DEFAULTS.dm), prompt: n.dm },
    source: { ...(current.source || DEFAULTS.source), queries: n.queries.slice() },
  };
}

